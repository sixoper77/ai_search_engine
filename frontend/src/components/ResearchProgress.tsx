import React, { useState } from 'react';
import { ChevronDown, ChevronUp, Globe, Loader2, Sparkles, CheckCircle2, Search } from 'lucide-react';
import { ResearchStep, SiteSource } from '../types';

interface ResearchProgressProps {
  steps: ResearchStep[];
  allSites: SiteSource[];
  isSearching: boolean;
  doneMessage?: string;
}

export const ResearchProgress: React.FC<ResearchProgressProps> = ({
  steps,
  allSites,
  isSearching,
  doneMessage,
}) => {
  const [isExpanded, setIsExpanded] = useState(true);

  if (steps.length === 0 && allSites.length === 0 && !isSearching) {
    return null;
  }

  const uniqueSites = Array.from(
    new Map(allSites.map((s) => [s.url, s])).values()
  );

  return (
    <div className="w-full max-w-3xl my-4 rounded-xl border border-[#2D3131] bg-[#1A1C1C] overflow-hidden text-sm shadow-sm animate-fade-in">
      {/* Header */}
      <button
        onClick={() => setIsExpanded(!isExpanded)}
        className="w-full flex items-center justify-between px-4 py-3 bg-[#202222] hover:bg-[#252828] transition-colors text-left"
      >
        <div className="flex items-center gap-2.5">
          {isSearching ? (
            <Loader2 className="w-4 h-4 text-[#20808D] animate-spin" />
          ) : (
            <CheckCircle2 className="w-4 h-4 text-emerald-400" />
          )}
          <span className="font-medium text-white flex items-center gap-2">
            <Sparkles className="w-3.5 h-3.5 text-[#20808D]" />
            {isSearching ? 'Агентный поиск Pro Search...' : 'Исследование завершено'}
          </span>
          {uniqueSites.length > 0 && (
            <span className="text-xs px-2 py-0.5 rounded-full bg-[#2A2E2E] text-[#9B9C9E]">
              {uniqueSites.length} {uniqueSites.length === 1 ? 'источник' : 'источников'}
            </span>
          )}
        </div>

        <div className="text-[#9B9C9E]">
          {isExpanded ? <ChevronUp className="w-4 h-4" /> : <ChevronDown className="w-4 h-4" />}
        </div>
      </button>

      {/* Expanded details */}
      {isExpanded && (
        <div className="p-4 space-y-4 border-t border-[#262929]">
          {/* Steps Timeline */}
          {steps.map((st) => (
            <div key={st.step} className="flex items-start gap-2.5 text-xs text-[#BABABA]">
              <div className="w-5 h-5 rounded-full bg-[#242727] border border-[#2D3131] flex items-center justify-center text-[10px] text-[#20808D] font-mono mt-0.5 flex-shrink-0">
                {st.step}
              </div>
              <div className="flex-1 space-y-1.5">
                <div className="flex items-center gap-2 flex-wrap">
                  <p className="font-medium text-[#E0E0E0]">{st.message}</p>
                  {st.info && (
                    <span className="text-[11px] text-[#8F9294] bg-[#222424] px-2 py-0.5 rounded border border-[#2B2E2E]">
                      {st.info}
                    </span>
                  )}
                </div>

                {/* Reason for needing more data (from reflection decision) */}
                {st.reason && (
                  <div className="text-[11px] text-[#C5C5C5] bg-[#202323] rounded-lg p-2.5 border border-[#2E3333] shadow-inner space-y-1">
                    <div className="text-[#20808D] font-medium flex items-center gap-1.5">
                      <Sparkles className="w-3 h-3" />
                      <span>Причина дополнительного поиска:</span>
                    </div>
                    <p className="text-[#A3A3A3] leading-relaxed">{st.reason}</p>
                  </div>
                )}

                {/* New search queries generated by reflection agent */}
                {st.newQueries && st.newQueries.length > 0 && (
                  <div className="flex flex-wrap gap-1.5 pt-0.5">
                    {st.newQueries.map((query, qIdx) => (
                      <span
                        key={qIdx}
                        className="inline-flex items-center gap-1 text-[11px] px-2 py-0.5 rounded-md bg-[#191B1B] text-[#38BDF8] border border-[#282B2B]"
                      >
                        <Search className="w-2.5 h-2.5 text-[#65686A]" />
                        <span>{query}</span>
                      </span>
                    ))}
                  </div>
                )}
              </div>
            </div>
          ))}

          {/* Consulted Websites */}
          {uniqueSites.length > 0 && (
            <div className="pt-2 border-t border-[#262929]/60">
              <span className="text-xs font-medium text-[#8F9294] block mb-2">
                Изученные веб-страницы:
              </span>
              <div className="flex flex-wrap gap-2">
                {uniqueSites.map((site, index) => {
                  let hostname = site.url;
                  try {
                    hostname = new URL(site.url).hostname.replace('www.', '');
                  } catch {
                    // ignore
                  }

                  return (
                    <a
                      key={index}
                      href={site.url}
                      target="_blank"
                      rel="noreferrer"
                      className="group flex items-center gap-1.5 px-2.5 py-1 rounded-lg bg-[#222424] hover:bg-[#2A2E2E] border border-[#2D3131] text-[11px] text-[#A3A3A3] hover:text-white transition-all max-w-[200px]"
                      title={site.title || site.url}
                    >
                      <Globe className="w-3 h-3 text-[#6E7173] group-hover:text-[#20808D] flex-shrink-0" />
                      <span className="truncate">{site.title || hostname}</span>
                    </a>
                  );
                })}
              </div>
            </div>
          )}

          {/* Final Done reflection reasoning */}
          {doneMessage && (
            <div className="text-xs text-[#8F9294] bg-[#1F2424]/70 p-2.5 rounded-lg border border-[#20808D]/30">
              <div className="text-emerald-400 font-medium text-[11px] flex items-center gap-1.5 mb-1">
                <CheckCircle2 className="w-3 h-3" />
                <span>Итог исследования:</span>
              </div>
              <p className="text-[#B5B5B5] leading-relaxed">{doneMessage}</p>
            </div>
          )}
        </div>
      )}
    </div>
  );
};
